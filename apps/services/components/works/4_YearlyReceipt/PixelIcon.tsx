export type PixelIconName = keyof typeof ICONS;

/** 행마다 이어진 칸을 하나의 rect로 합친 경로 */
const PATHS: Record<PixelIconName, string> = Object.fromEntries(
  Object.entries(ICONS).map(([name, rows]) => {
    let d = "";
    rows.forEach((row, y) => {
      let x = 0;
      while (x < row.length) {
        if (row[x] !== "#") {
          x++;
          continue;
        }
        const start = x;
        while (x < row.length && row[x] === "#") x++;
        d += `M${start} ${y}h${x - start}v1h${start - x}z`;
      }
    });
    return [name, d];
  }),
) as Record<PixelIconName, string>;

interface PixelIconProps {
  name: PixelIconName;
  /** 한 변 길이(px). 8의 배수일 때 가장 또렷하다 */
  size?: number;
  /** 지정하지 않으면 글자색(currentColor)을 따른다 */
  fill?: string;
  className?: string;
}

export default function PixelIcon({
  name,
  size = 16,
  fill = "currentColor",
  className,
}: PixelIconProps) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 8 8"
      shapeRendering="crispEdges"
      aria-hidden="true"
      className={className}
      style={{ flexShrink: 0 }}
    >
      <path d={PATHS[name]} fill={fill} />
    </svg>
  );
}
